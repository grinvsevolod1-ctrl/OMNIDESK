/**
 * The seller's system prompt: persona/tone/aggressiveness directives, the
 * objection-handling framework and the prompt assembly. This file IS the
 * seller's personality — every word here is read verbatim by the model.
 * Same dependency rules as the rest of lib/ai/brain/ (see core.ts).
 */

import type { ManagerBrainInput } from './core.js'

const TONE_HINT: Record<string, string> = {
  professional:
    'Деловой, вежливый, уверенный тон. Без панибратства, но по-человечески.',
  friendly: 'Дружелюбный, тёплый тон. Можно проще, но грамотно.',
  concise: 'Максимально коротко и по делу, без воды.',
  persuasive:
    'Убедительный, мотивирующий тон. Мягко ведёшь клиента к следующему шагу.',
}

function toneLine(tone: string): string {
  return TONE_HINT[tone] || TONE_HINT.professional
}

/** Clamp any incoming aggressiveness to 0..3, defaulting to 2 (assertive). */
function resolveAggressiveness(v: number | undefined): number {
  if (v == null || Number.isNaN(v)) return 2
  return Math.max(0, Math.min(3, Math.round(v)))
}

