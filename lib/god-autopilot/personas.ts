function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

/** Транслитерация имени в правдоподобный латинский хэндл. */
function toHandle(first: string, last: string): string {
  const map: Record<string, string> = {
    а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
    и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
    с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh',
    щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  }
  const tr = (s: string) =>
    s
      .toLowerCase()
      .split('')
      .map((ch) => map[ch] ?? '')
      .join('')
  const variants = [
    `${tr(first)}_${tr(last)}`,
    `${tr(first)}${tr(last)}`,
    `${tr(first)}.${tr(last)}`,
    `${tr(first)}${Math.floor(10 + Math.random() * 89)}`,
    `${tr(last)}_${tr(first)[0] ?? ''}`,
  ]
  return pick(variants)
}

/**
 * Собрать случайную персону. Комбинаторика пулов (архетип × манера × тон ×
 * цель × имя × город) даёт десятки тысяч непохожих вариантов.
 */
export function buildPersona(): AutopilotPersona {
  const female = Math.random() < 0.5
  const first = female ? pick(FIRST_NAMES_F) : pick(FIRST_NAMES_M)
  const last = pick(LAST_NAMES) + (female ? 'а' : '')
  return {
    name: `${first} ${last}`,
    handle: toHandle(first, last),
    city: pick(CITIES),
    archetype: pick(ARCHETYPES),
    style: pick(STYLES),
    mood: pick(MOODS),
    goal: pick(GOALS),
  }
}

/** Уникальный id для строк слотов (pgcrypto может быть не включён). */
export function newId(): string {
  return randomUUID()
}
