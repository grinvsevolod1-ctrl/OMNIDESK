-- 155_lead_card_rework_trash.sql
--
-- «Доработки»: когда куратор теряет лид (Игнор / Отказался / Не связался) или
-- отправляет его в архив, лид возвращается менеджеру на дожим. Если менеджер
-- тоже не смог дожать, он убирает лид из «Доработок» кнопкой «В trash».
--
-- Это ЧИСТО менеджерское терминальное поле: оно НЕ трогает кураторский enum
-- статусов лида и не меняет саму передачу — просто прячет карточку из раздела
-- «Доработки» у менеджера (деривация в managerBucket()). Nullable, по
-- умолчанию NULL = «ещё в дожиме».
ALTER TABLE lead_cards
  ADD COLUMN IF NOT EXISTS rework_trashed_at timestamptz;
