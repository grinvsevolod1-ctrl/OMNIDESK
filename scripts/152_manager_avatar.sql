-- 152_manager_avatar.sql
-- Аватарки сотрудников (менеджер / куратор / руководитель / медиабайер).
--
-- Хранение СТРОГО локальное, без сторонних сервисов: картинка приходит уже
-- сжатой на клиенте (canvas → квадрат 256×256, JPEG/WebP) и кладётся в БД как
-- data:-URL прямо в это TEXT-поле. Ограничение размера — на сервере в
-- updateMyAvatarAction (см. app/actions/account-profile.ts). Все четыре роли
-- живут в одной таблице managers (см. миграции 111/141/145), поэтому одного
-- столбца достаточно. Админ — env-only, у него строки нет, аватарки у него нет.
ALTER TABLE managers
  ADD COLUMN IF NOT EXISTS avatar_url TEXT;
