-- ============================================================
-- 3) Канонизация городов кураторов + чистка мусора
-- ============================================================

-- 3.1 Канонизируем валидные записи (есть в справочнике с регионом или
--     совпадают с названием региона): приводим к каноническому написанию.
UPDATE curator_cities cc
SET city = c.name
FROM cities c
WHERE c.name_norm = cc.city_norm
  AND c.region_id IS NOT NULL
  AND cc.city <> c.name;

UPDATE curator_cities cc
SET city = r.name
FROM regions r
WHERE r.name_norm = cc.city_norm
  AND cc.city <> r.name;

-- 3.2 Удаляем записи кураторов, которых нет ни среди городов с регионом,
--     ни среди регионов.
DELETE FROM curator_cities cc
WHERE NOT EXISTS (
        SELECT 1 FROM cities c
        WHERE c.name_norm = cc.city_norm AND c.region_id IS NOT NULL)
  AND NOT EXISTS (
        SELECT 1 FROM regions r WHERE r.name_norm = cc.city_norm);

-- 3.3 Кураторам, оставшимся без городов, назначаем первый город базы.
INSERT INTO curator_cities (curator_id, city, city_norm)
SELECT m.id, fc.name, fc.name_norm
FROM managers m
CROSS JOIN LATERAL (
  SELECT name, name_norm FROM cities
  WHERE region_id IS NOT NULL
  ORDER BY name ASC LIMIT 1
) fc
WHERE m.role = 'curator'
  AND NOT EXISTS (SELECT 1 FROM curator_cities cc WHERE cc.curator_id = m.id)
ON CONFLICT (curator_id, city_norm) DO NOTHING;

-- 3.4 Синхронизируем основной город менеджера по кадрам (managers.city).
UPDATE managers m
SET city = pick.city
FROM (
  SELECT DISTINCT ON (curator_id) curator_id, city
  FROM curator_cities
  ORDER BY curator_id, city ASC
) pick
WHERE m.id = pick.curator_id
  AND m.role = 'curator'
  AND (m.city IS NULL OR lower(m.city) NOT IN (
        SELECT city_norm FROM curator_cities cc2 WHERE cc2.curator_id = m.id));

-- 3.5 Чистим мусорные города без региона из справочника (произвольный ввод
--     прошлых версий). Города лидов хранятся текстом — данные лидов целы.
DELETE FROM cities WHERE region_id IS NULL;
