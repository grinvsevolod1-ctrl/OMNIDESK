-- 124: Полная база городов РФ + регионы как значения города.
--
-- 1) regions.aliases: разговорные названия («Чечня» → «Чеченская Республика»)
--    для автодополнения.
-- 2) Полный сид городов РФ по регионам (все города, ~1100). Существующие
--    записи получают region_id (COALESCE: уже привязанные не трогаем).
--    ВНИМАНИЕ: name_norm UNIQUE — города-тёзки (Киров, Советск, Железногорск…)
--    хранятся одной строкой; регион у тёзки остаётся первый назначенный.
-- 3) Чистка справочника: удаляем «мусорные» города без региона (произвольный
--    ввод прошлых версий), предварительно канонизировав города кураторов.
-- 4) curator_cities: города не из справочника заменяются первым городом базы;
--    существующие валидные приводятся к каноническому написанию.

