-- 137: единый постоянный API-ключ для god-сайтов.
--
-- Раньше каждое скачивание расширения РОТИРОВАЛО ключ (прежние архивы сразу
-- умирали). По решению владельца ключ теперь один и вечный: plaintext хранится
-- рядом с хэшем, все скачанные архивы работают одновременно.
--
-- Легаси: у существующих сайтов plaintext из хэша невосстановим — колонка
-- остаётся NULL до первого обращения (getOrCreateSiteKey), которое один
-- финальный раз перевыпускает ключ и с этого момента фиксирует его навсегда.
-- Старые архивы таких сайтов работают до этой перевыпуски.

ALTER TABLE god_sites
  ADD COLUMN IF NOT EXISTS api_key_plain TEXT;
