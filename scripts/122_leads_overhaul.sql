CREATE TABLE IF NOT EXISTS vacancies (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name       TEXT NOT NULL,
  name_norm  TEXT NOT NULL UNIQUE,
  active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO vacancies (name, name_norm)
VALUES ('Курьер', 'курьер'), ('Водитель', 'водитель')
ON CONFLICT (name_norm) DO NOTHING;

-- Backfill из уже введённых значений должностей.
INSERT INTO vacancies (name, name_norm)
SELECT DISTINCT ON (norm) trim(regexp_replace(vacancy, '\s+', ' ', 'g')) AS name,
       lower(trim(regexp_replace(vacancy, '\s+', ' ', 'g'))) AS norm
  FROM lead_cards
 WHERE vacancy IS NOT NULL AND btrim(vacancy) <> ''
ON CONFLICT (name_norm) DO NOTHING;

